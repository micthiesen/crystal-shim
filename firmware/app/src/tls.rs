/// A validated UTC value suitable for X.509 validity checks.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct UtcDateTime {
    year: u16,
    month: u8,
    day: u8,
    hour: u8,
    minute: u8,
    second: u8,
}

/// Why a UTC value cannot be used for certificate verification.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum DateTimeError {
    Year,
    Month,
    Day,
    Hour,
    Minute,
    Second,
}

impl UtcDateTime {
    /// Validates a Gregorian UTC date. Leap seconds are deliberately rejected.
    pub const fn new(
        year: u16,
        month: u8,
        day: u8,
        hour: u8,
        minute: u8,
        second: u8,
    ) -> Result<Self, DateTimeError> {
        if year < 1970 || year > 9999 {
            return Err(DateTimeError::Year);
        }
        if month < 1 || month > 12 {
            return Err(DateTimeError::Month);
        }
        if day < 1 || day > days_in_month(year, month) {
            return Err(DateTimeError::Day);
        }
        if hour > 23 {
            return Err(DateTimeError::Hour);
        }
        if minute > 59 {
            return Err(DateTimeError::Minute);
        }
        if second > 59 {
            return Err(DateTimeError::Second);
        }

        Ok(Self {
            year,
            month,
            day,
            hour,
            minute,
            second,
        })
    }

    fn as_tm(self) -> tm {
        tm {
            tm_sec: i32::from(self.second),
            tm_min: i32::from(self.minute),
            tm_hour: i32::from(self.hour),
            tm_mday: i32::from(self.day),
            tm_mon: i32::from(self.month) - 1,
            tm_year: i32::from(self.year) - 1900,
            tm_wday: i32::from(weekday(self.year, self.month, self.day)),
            tm_yday: i32::from(day_of_year(self.year, self.month, self.day)) - 1,
            tm_isdst: 0,
        }
    }

    fn advance_seconds(mut self, elapsed: u32) -> Option<Self> {
        let seconds =
            u32::from(self.hour) * 3_600 + u32::from(self.minute) * 60 + u32::from(self.second);
        let advanced = seconds.checked_add(elapsed)?;
        self.second = (advanced % 60) as u8;
        self.minute = (advanced / 60 % 60) as u8;
        self.hour = (advanced / 3_600 % 24) as u8;

        // The freshness limit bounds this to at most one midnight per read.
        for _ in 0..advanced / 86_400 {
            self.day += 1;
            if self.day > days_in_month(self.year, self.month) {
                self.day = 1;
                self.month += 1;
                if self.month > 12 {
                    self.month = 1;
                    self.year = self.year.checked_add(1)?;
                    if self.year > 9999 {
                        return None;
                    }
                }
            }
        }
        Some(self)
    }
}

struct CertificateClock;

#[derive(Clone, Copy)]
struct TrustedUtc {
    utc: UtcDateTime,
    anchored_at_ms: i64,
    last_checked_ms: i64,
}

impl TrustedUtc {
    fn at(&mut self, monotonic_ms: i64) -> Option<UtcDateTime> {
        // Both timer backends saturate at i64::MAX. Reject saturation as well
        // as observed rollback so an exhausted or reset timer cannot freeze UTC.
        if monotonic_ms < self.last_checked_ms || monotonic_ms == i64::MAX {
            return None;
        }
        let elapsed = monotonic_ms.checked_sub(self.anchored_at_ms)?;
        if !(0..TRUSTED_UTC_MAX_AGE_MS).contains(&elapsed) {
            return None;
        }
        self.last_checked_ms = monotonic_ms;
        self.utc.advance_seconds((elapsed / 1_000) as u32)
    }
}

