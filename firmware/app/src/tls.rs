/// Installs the process-wide clocks used by MbedTLS.
///
/// Until set_trusted_utc supplies a value, MbedTLS rejects certificate validation.
///
/// # Safety
///
/// Call this exactly once during single-threaded startup, before any MbedTLS
/// operation that can perform X.509 validation or use the monotonic timer. The
/// installed clocks are static and this module never replaces or removes them.
pub unsafe fn install_certificate_clock() {
    // SAFETY: the hook points at an immutable static object for the rest of the
    // process. Installation happens during startup; this module never removes or
    // replaces the hook.
    unsafe {
        hook_timer(Some(&TLS_TIMER));
        hook_wall_clock(Some(&CERTIFICATE_CLOCK));
    }
}

/// Anchors a newly acquired, trusted UTC observation to the monotonic clock.
///
/// The caller must validate its source and freshness before publishing. Do not
/// republish a cached observation: that would incorrectly renew its trust.
/// UTC advances automatically and expires at TRUSTED_UTC_MAX_AGE_MS.
pub fn set_trusted_utc(now: UtcDateTime) {
    critical_section::with(|cs| {
        let monotonic_ms = TLS_TIMER.now();
        let anchor = (0..i64::MAX).contains(&monotonic_ms).then_some(TrustedUtc {
            utc: now,
            anchored_at_ms: monotonic_ms,
            last_checked_ms: monotonic_ms,
        });
        TRUSTED_UTC.borrow(cs).set(anchor);
    });
}

/// Clears UTC after the clock loses trust. New handshakes then fail closed.
pub fn clear_trusted_utc() {
    critical_section::with(|cs| TRUSTED_UTC.borrow(cs).set(None));
}

/// Reports whether UTC is available and still within its monotonic age limit.
pub fn has_trusted_utc() -> bool {
    trusted_utc().is_some()
}

fn trusted_utc() -> Option<UtcDateTime> {
    critical_section::with(|cs| {
        let cell = TRUSTED_UTC.borrow(cs);
        let mut anchor = cell.get()?;
        // Read time and update the anchor under the same lock: a concurrent
        // refresh/read must not appear to move the monotonic clock backwards.
        let utc = anchor.at(TLS_TIMER.now());
        // Expiry, rollback, saturation, and calendar overflow stay invalid until
        // a new trusted observation arrives, even if the timer later recovers.
        cell.set(utc.map(|_| anchor));
        utc
    })
}

/// Error constructing the fixed Pushover connector policy.
#[derive(Debug)]
pub enum ProviderError {
    /// Certificate verification cannot run without trusted UTC.
    ClockUnavailable,
    /// The embedded trust anchor could not be parsed.
    TrustAnchor(SessionError),
}

/// Wraps an edge-nal TCP connector with the fixed, verified Pushover policy.
///
/// The returned connector requires a chain to DigiCert Global Root G2, verifies
/// api.pushover.net, requires certificate dates to contain the hooked UTC value,
/// and requires TLS 1.2.
pub fn pushover_connector<'a, T>(
    tls: TlsReference<'a>,
    tcp: T,
) -> Result<TlsConnector<'a, T>, ProviderError>
where
    T: TcpConnect,
{
    let config = pushover_config()?;
    Ok(TlsConnector::new(tls, tcp, &config))
}

fn pushover_config() -> Result<ClientSessionConfig<'static>, ProviderError> {
    require_trusted_utc()?;

    let ca_chain = Certificate::new_no_copy(DIGICERT_GLOBAL_ROOT_G2_DER)
        .map_err(ProviderError::TrustAnchor)?;
    Ok(ClientSessionConfig {
        ca_chain: Some(ca_chain),
        creds: None,
        server_name: Some(PUSHOVER_HOST),
        auth_mode: AuthMode::Required,
        min_version: TlsVersion::Tls1_2,
        alpn_protocols: None,
    })
}

fn require_trusted_utc() -> Result<(), ProviderError> {
    has_trusted_utc()
        .then_some(())
        .ok_or(ProviderError::ClockUnavailable)
}

const fn is_leap_year(year: u16) -> bool {
    year.is_multiple_of(4) && (!year.is_multiple_of(100) || year.is_multiple_of(400))
}

const fn days_in_month(year: u16, month: u8) -> u8 {
    match month {
        2 if is_leap_year(year) => 29,
        2 => 28,
        4 | 6 | 9 | 11 => 30,
        _ => 31,
    }
}

const fn day_of_year(year: u16, month: u8, day: u8) -> u16 {
    let mut current = 1;
    let mut ordinal = day as u16;

    while current < month {
        ordinal += days_in_month(year, current) as u16;
        current += 1;
    }

    ordinal
}

const fn weekday(year: u16, month: u8, day: u8) -> u8 {
    let offsets = [0_u32, 3, 2, 5, 0, 3, 5, 1, 4, 6, 2, 4];
    let mut adjusted_year = year as u32;
    if month < 3 {
        adjusted_year -= 1;
    }

    ((adjusted_year + adjusted_year / 4 - adjusted_year / 100
        + adjusted_year / 400
        + offsets[(month - 1) as usize]
        + day as u32)
        % 7) as u8
}

